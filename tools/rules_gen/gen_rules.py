def gen_globals():
    values = {}
    for _, header, rows in tables(SPEC / "global-parameters.md"):
        if header[:2] != ["Parameter", "Value"]:
            continue
        for row in rows:
            try:
                values[row["Parameter"]] = num(row["Value"])
            except ValueError:
                pass  # text-valued parameters are not rules numbers
    return {"globals": dict(sorted(values.items())), "happinessLevels": gen_happiness(),
            "loyaltyLevels": gen_loyalty_levels()}


def gen_improvements():
    tnames = terrain_names()
    resources = {}
    for sec in ("Bonus resources", "Luxury resources", "Strategic resources"):
        for r in table(SPEC / "terrain-features-resources.md", sec):
            resources[r["Resource"]] = "RESOURCE_" + snake(r["Resource"])
    # City-states' unique improvements: built by the Builders of whoever enjoys the city-state's suzerain bonus (08).
    city_states = {r["City-state"]: "CITYSTATE_" + snake(r["City-state"]) for r in table(SPEC / "city-states.md", "City-states and suzerain bonuses")}
    # "Civilization No Player" marks improvements a governor opens (Liang's Fishery and City Park; 08).
    rows = [r for r in table(SPEC / "improvements.md", "Improvements")
            if r["Built by"] in ("Builder", "Military Engineer") and (not r["Unique to"] or r["Unique to"] in city_states
                                                                     or r["Unique to"] == "Civilization No Player")]
    ids = {r["Improvement"]: "IMPROVEMENT_" + snake(r["Improvement"]) for r in rows}
    districts = {r["District"]: "DISTRICT_" + snake(r["District"]) for r in table(SPEC / "districts.md", "District stats") if not r.get("Unique to")}
    adjacent_kinds = {"district": ("district", "ANY"), "Bonus resource": ("resourceClass", "BONUS"), "Luxury resource": ("resourceClass", "LUXURY"),
                      "Woods": ("feature", "FEATURE_FOREST"), "Rainforest": ("feature", "FEATURE_JUNGLE"), "Reef": ("feature", "FEATURE_REEF"),
                      "sea resource": ("seaResource", True)}  # the Seastead's Reefs; any resource on water, for the Fishery
    out = []
    for row in rows:
        i = {"id": ids[row["Improvement"]], "name": row["Improvement"], "yields": yields(row["Base yields"])}
        if row["Unique to"] == "Civilization No Player":
            # Built only in a city whose governor holds the promotion, which also adds its yield there.
            m = re.search(r"\+(\d+) (\w+) on this tile where city has governor with (.+?)(?:;|$)", row["Modifiers"] or "")
            i["governorPromotion"] = "GOVERNOR_PROMOTION_" + snake(m.group(3))
            i["governorYields"] = {YIELD_WORDS[m.group(2)]: int(m.group(1))}
            if "+1 Amenity where plot adjacent to coast" in (row["Modifiers"] or ""):
                i["waterAmenity"] = 1  # the City Park: +1 Amenity beside the coast, a lake or a river
        elif row["Unique to"]:
            i["cityState"] = city_states[row["Unique to"]]
        if row["Unlock"]:
            i["unlock"] = unlock_id(row["Unlock"])
        terr, feat = [], []
        for v in (x.strip() for x in row["Valid terrain/feature"].split(",")):
            if not v:
                continue
            if v in tnames:
                terr.append(tnames[v])
            elif v in FEATURE_IDS:
                feat.append(FEATURE_IDS[v])
            elif v == "Mountain":
                terr += [tnames[b] + "_MOUNTAIN" for b in ("Grassland", "Plains", "Desert", "Tundra", "Snow")]
            else:
                raise ValueError(f"improvement {row['Improvement']}: unknown place {v!r}")
        i["validTerrains"], i["validFeatures"] = terr, feat
        i["validResources"] = [resources[x.strip()] for x in row["Valid resources"].split(",") if x.strip()]
        bonus = []
        for part in filter(None, (x.strip() for x in row["Bonus yields"].split(","))):
            m = re.fullmatch(r"\+(\d+) (\w+) With (.+)", part)
            bonus.append({"yield": YIELD_WORDS[m.group(2)], "amount": int(m.group(1)), "unlock": unlock_id(m.group(3))})
        if bonus:
            i["bonusYields"] = bonus
        adjacency = []
        for part in filter(None, (x.strip() for x in row["Adjacency"].split(";"))):
            m = re.fullmatch(r"\+(\d+) (\w+) per (?:(\d+) )?(.+?)(?: \((.+)\))?", part)
            if not m or not (m.group(4) in ids or m.group(4) in districts or m.group(4) in adjacent_kinds):
                continue  # adjacency to unique districts and civs' unique improvements arrives with them
            a = {"yield": YIELD_WORDS[m.group(2)], "amount": int(m.group(1)), "per": int(m.group(3) or 1)}
            if m.group(4) in ids:
                a["improvement"] = ids[m.group(4)]
            elif m.group(4) in districts:
                a["district"] = districts[m.group(4)]
            else:
                key, value = adjacent_kinds[m.group(4)]
                a[key] = value
            for cond in filter(None, (c.strip() for c in (m.group(5) or "").split(","))):
                c = re.fullmatch(r"(needs|obsolete with) (.+)", cond)
                a["needs" if c.group(1) == "needs" else "obsoleteWith"] = unlock_id(c.group(2))
            adjacency.append(a)
        if adjacency:
            i["adjacency"] = adjacency
        m = re.fullmatch(r"(\d+)(?: \(per (\d+) tiles\))?", row["Housing"])
        if m and int(m.group(1)):
            i["housing"] = int(m.group(1)) / int(m.group(2) or 1)
        if row["Appeal"] and num(row["Appeal"]):
            i["appeal"] = num(row["Appeal"])  # to neighbouring plots (01: Appeal)
        kind, amount = IMPROVEMENT_PLUNDER.get(row["Improvement"], ("GOLD", 25))
        i["plunder"] = {"kind": kind, "amount": amount}
        if row["Defense"] and num(row["Defense"]):
            i["defense"] = num(row["Defense"])  # Fort; Granada's Alcázar
        if row["Built by"] == "Military Engineer":
            i["builtBy"] = "UNIT_MILITARY_ENGINEER"  # Fort, Airstrip, Missile Silo
            if row["Improvement"] == "Airstrip":
                i["airSlots"] = 3  # 03: Airstrip, 3 air slots
            if row["Improvement"] == "Mountain Tunnel":
                i["tunnel"] = True  # 01: makes the mountain passable
        m = re.search(r"\+(\d+) Power \(Free Power Source", row["Modifiers"] or "")
        if m:
            i["powerProvided"] = int(m.group(1))  # renewables (09: Power)
        # Tourism (07: Tourism sources): "TOURISMSOURCE_APPEAL x100% after " or "... after TECH_FLIGHT".
        m = re.fullmatch(r"TOURISMSOURCE_(\w+) x(\d+)% after ?(\w*)", (row["Tourism"] or "").strip())
        if m:
            i["tourism"] = {"source": m.group(1), "percent": int(m.group(2))}
            if m.group(3):
                i["tourism"]["after"] = m.group(3)
        if row["Min appeal"] and num(row["Min appeal"]):
            i["minAppeal"] = num(row["Min appeal"])
        # Modifiers (08: the city-states' improvements): yields on its own plot when the plot qualifies (the Moai beside the
        # coast, or on or beside Volcanic Soil), yields on its owner's plots beside it (the Nazca Line) and Amenities.
        tile, near, amenity_sides = [], [], {}
        for part in (x.strip() for x in (row["Modifiers"] or "").split(";")):
            m = re.fullmatch(r"\+(\d+) Amenity in this city", part)
            if m:
                i["amenities"] = int(m.group(1))  # the Ski Resort (07)
            # The Temple of Artemis (03): a Camp, Pasture or Plantation this near it gives its city an Amenity.
            m = re.fullmatch(r"\+(\d+) Amenity where within (\d+) tiles of (.+)", part)
            if m:
                i["wonderAmenity"] = {"wonder": "BUILDING_" + snake(m.group(3)), "range": int(m.group(2)), "amount": int(m.group(1))}
            m = re.fullmatch(r"\+(\d+) Amenity in this city where (NOT )?has (.+)", part)
            if m:
                amenity_sides.setdefault((int(m.group(1)), m.group(3)), set()).add(bool(m.group(2)))
            m = re.fullmatch(r"\+(\d+) (\w+) on this tile where plot is coast or plot adjacent to coast", part)
            if m:
                tile.append({"yield": YIELD_WORDS[m.group(2)], "amount": int(m.group(1)), "nextToCoast": True})
            m = re.fullmatch(r"\+(\d+) (\w+) on this tile where adjacent to (.+?) or tile is \3", part)
            if m and m.group(3) in FEATURE_IDS:
                tile.append({"yield": YIELD_WORDS[m.group(2)], "amount": int(m.group(1)), "nearFeature": FEATURE_IDS[m.group(3)]})
            # "within tiles" gives no distance: Sovereign reads it as the plots beside the improvement.
            m = re.fullmatch(r"\+(\d+) (\w+) on your tiles where within tiles((?: and .+?)*)", part)
            if m:
                n = {"yield": YIELD_WORDS[m.group(2)], "amount": int(m.group(1))}
                for cond in filter(None, m.group(3).split(" and ")):
                    if cond == "plot has any resource":
                        n["resource"] = True
                    elif cond == "NOT tile is Hills":
                        n["notHills"] = True
                    elif cond.startswith("tile is ") and cond[len("tile is "):] in tnames:
                        n["terrain"] = tnames[cond[len("tile is "):]]
                    elif cond.startswith("has "):
                        n["needs"] = unlock_id(cond[len("has "):])
                    else:
                        raise ValueError(f"improvement {row['Improvement']}: unknown condition {cond!r}")
                near.append(n)
        # Cahokia Mounds: +1 Amenity before Natural History and +1 after it, so always 1.
        for (amount, _), sides in amenity_sides.items():
            if sides == {True, False}:
                i["amenities"] = i.get("amenities", 0) + amount
        if tile:
            i["tileYields"] = tile
        if near:
            i["neighbourYields"] = near
        if row["Improvement"] == "Seaside Resort":
            i["coastal"] = True  # 07: built on the coast (the terrain list leaves it out)
        # Improvements that work the sea (the Improvements table's Domain, which the extract leaves out): Fishing Boats,
        # and those whose land is water only. A resource found on both (Amber, Oil) takes the improvement of its own.
        if row["Improvement"] == "Fishing Boats" or (terr and all(t in ("TERRAIN_COAST", "TERRAIN_OCEAN") for t in terr)):
            i["water"] = True
        out.append(i)
    return {"improvements": out}


# ------------------------------------------------------------ research trees

ERAS = ["Ancient", "Classical", "Medieval", "Renaissance", "Industrial", "Modern", "Atomic",
        "Information", "Future"]


def tree_rows(kind):
    """(era id, row) for every node of the tech ("technologies") or civic ("civics") tree."""
    for section, _, rows in tables(SPEC / f"{kind}.md"):
        m = re.fullmatch(r"(\w+) Era", section or "")
        if m and m.group(1) in ERAS:
            for row in rows:
                yield "ERA_" + m.group(1).upper(), row


def node_names():
    names = {}
    for era, row in tree_rows("technologies"):
        names[row["Technology"]] = "TECH_" + snake(row["Technology"])
    for era, row in tree_rows("civics"):
        names[row["Civic"]] = "CIVIC_" + snake(row["Civic"])
    return names


def unlock_id(name):
    ids = node_names()
    if name not in ids:
        raise ValueError(f"unlock {name!r} is neither a technology nor a civic")
    return ids[name]


def singulars(name):
    yield name
    if name.endswith("ies"):
        yield name[:-3] + "y"
    if name.endswith("s"):
        yield name[:-1]
    if name.endswith("es"):
        yield name[:-2]


def lookup(name, ids):
    for n in singulars(name):
        if n in ids:
            return ids[n]
    return None


def boost_trigger(text, era=None):
    """Turn a boost condition into {type, ref, count}. "NONE" means no condition
    can earn it; conditions the rules core cannot read are "UNTRACKED". `era` is
    the node's own era (for "a wonder of a later era")."""
    units = {r["Unit"]: "UNIT_" + snake(r["Unit"]) for r in table(SPEC / "units.md", "Units") if not r.get("Unique to")}
    buildings = {r["Building"]: "BUILDING_" + snake(r["Building"])
                 for r in table(SPEC / "buildings.md", "Buildings") if not r.get("Unique to")}
    districts = {r["District"]: "DISTRICT_" + snake(r["District"])
                 for r in table(SPEC / "districts.md", "District stats") if not r.get("Unique to")}
    improvements = {r["Improvement"]: "IMPROVEMENT_" + snake(r["Improvement"])
                    for r in table(SPEC / "improvements.md", "Improvements") if not r.get("Unique to")}
    resources = {}
    for sec in ("Bonus resources", "Luxury resources", "Strategic resources"):
        for r in table(SPEC / "terrain-features-resources.md", sec):
            resources[r["Resource"]] = "RESOURCE_" + snake(r["Resource"])
    nodes = node_names()
    t = (text or "").strip()
    count = lambda w: 1 if w in ("a", "an") else int(w)
    m = re.fullmatch(r"build (a|an|\d+) (.+?)( on a resource)?", t)
    if m:
        n, what, on_res = count(m.group(1)), m.group(2), bool(m.group(3))
        if on_res and lookup(what, improvements):
            return {"type": "IMPROVEMENT_ON_RESOURCE", "ref": lookup(what, improvements), "count": n}
        for kind, ids in (("BUILDING", buildings), ("DISTRICT", districts), ("IMPROVEMENT", improvements)):
            ref = lookup(what, ids)
            if ref and not on_res:
                return {"type": kind, "ref": ref, "count": n}
    m = re.fullmatch(r"(?:own|train) (a|an|\d+) (.+)", t)
    if m and lookup(m.group(2), units):
        return {"type": "OWN_UNITS", "ref": lookup(m.group(2), units), "count": count(m.group(1))}
    m = re.fullmatch(r"research (.+)", t)
    if m and m.group(1) in nodes:
        return {"type": "TECH", "ref": nodes[m.group(1)]}
    m = re.fullmatch(r"complete the civic (.+)", t)
    if m and m.group(1) in nodes:
        return {"type": "CIVIC", "ref": nodes[m.group(1)]}
    m = re.fullmatch(r"adopt a Tier(\d) government", t)
    if m:
        return {"type": "GOVERNMENT_TIER", "count": int(m.group(1))}
    m = re.fullmatch(r"reach (\d+) total population", t)
    if m:
        return {"type": "TOTAL_POPULATION", "count": int(m.group(1))}
    m = re.fullmatch(r"grow a city to (\d+) population", t)
    if m:
        return {"type": "CITY_POPULATION", "count": int(m.group(1))}
    m = re.fullmatch(r"have (\d+) land combat units", t)
    if m:
        return {"type": "LAND_COMBAT_UNITS", "count": int(m.group(1))}
    if t == "found a coastal city":
        return {"type": "COASTAL_CITY"}
    m = re.fullmatch(r"improve (.+)", t)
    if m and m.group(1) in resources:
        return {"type": "IMPROVE_RESOURCE", "ref": resources[m.group(1)]}
    m = re.fullmatch(r"improve (\d+) tiles", t)
    if m:
        return {"type": "IMPROVED_TILES", "count": int(m.group(1))}
    m = re.fullmatch(r"have (\d+) different specialty districts", t)
    if m:
        return {"type": "SPECIALTY_DISTRICTS", "count": int(m.group(1))}
    m = re.fullmatch(r"have (a|an|\d+) trade routes?", t)
    if m:
        return {"type": "TRADE_ROUTES", "count": count(m.group(1))}
    if t == "meet another civilization":
        return {"type": "MET_CIVS", "count": 1}
    m = re.fullmatch(r"meet (\d+) city-states", t)
    if m:
        return {"type": "MET_CITY_STATES", "count": int(m.group(1))}
    if t in ("found a pantheon", "found a religion"):
        return {"type": t.split()[-1].upper()}
    m = re.fullmatch(r"have (\d+) cities following your religion", t)
    if m:
        return {"type": "FOLLOWING_CITIES", "count": int(m.group(1))}
    m = re.fullmatch(r"have an alliance|have a level (\d+) alliance", t)
    if m:
        return {"type": "ALLIANCE", "count": int(m.group(1) or 1)}
    m = re.fullmatch(r"earn (\d+) Great People", t)
    if m:
        return {"type": "GREAT_PEOPLE", "count": int(m.group(1))}
    m = re.fullmatch(r"have (\d+) (corps|armies)", t)
    if m:
        return {"type": m.group(2).upper(), "count": int(m.group(1))}
    m = re.fullmatch(r"have an? (.+) with appeal (\d+)\+", t)
    if m and lookup(m.group(1), districts):
        return {"type": "DISTRICT_APPEAL", "ref": lookup(m.group(1), districts), "count": int(m.group(2))}
    m = re.fullmatch(r"have (a|\d+) themed buildings?", t)
    if m:
        return {"type": "THEMED_BUILDINGS", "count": count(m.group(1))}
    m = re.fullmatch(r"build an? (.+) next to a mountain", t)
    if m and lookup(m.group(1), buildings):
        return {"type": "BUILDING_NEXT_TO_MOUNTAIN", "ref": lookup(m.group(1), buildings)}
    m = re.fullmatch(r"build (a|\d+) wonders?", t)
    if m:
        return {"type": "WONDERS", "count": count(m.group(1))}
    eras = ["ERA_" + e.upper() for e in ERAS]
    if t == "build a wonder of a later era" and era in eras[1:]:
        # The table drops the era: Civ VI asks for a wonder of the era before the node's or later (Buttress: Classical,
        # Flight: Industrial; 04).
        return {"type": "WONDER_FROM_ERA", "era": eras[eras.index(era) - 1]}
    m = re.fullmatch(r"have an? (.+?) and an? (.+?)(?: on (.+))?", t)
    if m and lookup(m.group(1), units) and lookup(m.group(2), improvements) and (not m.group(3) or m.group(3) in resources):
        b = {"type": "UNIT_AND_IMPROVEMENT", "ref": lookup(m.group(1), units), "improvement": lookup(m.group(2), improvements)}
        if m.group(3):
            b["resource"] = resources[m.group(3)]
        elif b["improvement"] == "IMPROVEMENT_MINE" and b["ref"] == "UNIT_IRONCLAD":
            b["resource"] = "RESOURCE_COAL"  # tables extracted before the resource was named: Steel's is a Coal Mine (04)
        return b
    if t == "build an aerodrome/airstrip on a foreign continent":
        return {"type": "AIR_BASE_ABROAD"}
    m = re.fullmatch(r"discover a second continent|discover (\d+) continents", t)
    if m:
        return {"type": "CONTINENTS", "count": int(m.group(1) or 2)}
    m = re.fullmatch(r"kill (\d+) barbarians", t)
    if m:
        return {"type": "BARBARIAN_KILLS", "count": int(m.group(1))}
    # Events, earned as they happen.
    m = re.fullmatch(r"kill a unit with an? (.+)", t)
    if m and lookup(m.group(1), units):
        return {"type": "KILL_WITH", "ref": lookup(m.group(1), units)}
    m = re.fullmatch(r"kill an? (.+)", t)
    if m and lookup(m.group(1), units):
        return {"type": "KILL_UNIT", "ref": lookup(m.group(1), units)}
    events = {"clear a barbarian camp": "CLEAR_CAMP", "be the target of a war declaration": "WAR_DECLARED_ON",
              "declare war using a casus belli": "CASUS_BELLI_WAR", "extract an artifact": "ARTIFACT",
              "create a National Park": "NATIONAL_PARK", "discover a natural wonder": "NATURAL_WONDER"}
    if t in events:
        return {"type": events[t]}
    if not t or t.lower().startswith("none"):
        return {"type": "NONE"}
    return {"type": "UNTRACKED"}


def era_turns(row):
    """Era length bounds and the age threshold shift (09: Era score and Ages)."""
    out = {}
    m = re.fullmatch(r"(\d+)/(\d+)", row["Min / max turns [R&F]"] or "")
    if m:
        out["minTurns"], out["maxTurns"] = int(m.group(1)), int(m.group(2))
    if row["Era score threshold shift [GS]"]:
        out["eraScoreShift"] = num(row["Era score threshold shift [GS]"])
    return out


DISASTER_KINDS = [("Flood", "FLOOD"), ("Eruption", "ERUPTION"), ("Blizzard", "BLIZZARD"), ("Dust Storm", "DUST_STORM"),
                  ("Tornado", "TORNADO"), ("Hurricane", "HURRICANE"), ("Drought", "DROUGHT"), ("Forest Fire", "FIRE"),
                  ("Radioactive Steam Venting", "NUCLEAR"), ("Major Radiation Leak", "NUCLEAR"), ("Nuclear Meltdown", "NUCLEAR"),
                  ("Meteor Shower", "METEOR")]


# The volcano natural wonders the disaster table names by the game's ids, where ours differ.
NATURAL_WONDER_EVENT_FEATURES = {"FEATURE_KILIMANJARO": "FEATURE_MOUNT_KILIMANJARO", "FEATURE_VESUVIUS": "FEATURE_MOUNT_VESUVIUS"}


def gen_disasters():
    """Natural disasters the core runs (09: Climate and Disasters [GS]; data: climate-disasters.md):
    frequency per game by Disaster Intensity, damage, fertility afterwards; the climate phases;
    intensity settings; nuclear accidents at aging reactors; meteor showers (their meteor sites are left out);
    the eruptions of the volcano natural wonders (Mount Kilimanjaro, Mount Vesuvius, Eyjafjallajökull), each its
    own event at that wonder, listed after the others."""
    path = SPEC / "climate-disasters.md"
    # Storm rows name Ice as their feature: the engine's stand-in for any affected land tile.
    storm_kinds = {"BLIZZARD", "DUST_STORM", "TORNADO", "HURRICANE"}
    events, wonder_events, phases = [], [], []
    # The later tables give an event name's rows in one run per event row of that name, in the same order
    # (Kilimanjaro's or Vesuvius' eruption, then any volcano's, then Eyjafjallajokull's), so each event row
    # keeps its own run. A second ordinary row of a name (the jungle's Forest Fire) adds nothing.
    variants = {}
    for r in table(path, "Random events (disasters)"):
        name = r["RandomEventType"]
        if name.startswith("Climate Change Phase"):
            phases.append({"id": "CLIMATE_PHASE_" + name.split()[-1], "name": name, "points": num(r["ClimateChangePoints"]),
                           "iceLoss": num(r["IceLoss"]), "fertilityRemoval": num(r["FertilityRemovalChance"])})
            continue
        kind = next((k for word, k in DISASTER_KINDS if word in name), None)
        slot = variants.setdefault(name, [])
        if not kind or (not r["NaturalWonder"] and any(e and "naturalWonder" not in e for e in slot)):
            slot.append(None)
            continue
        e = {"id": "DISASTER_" + snake(name), "name": name, "kind": kind, "severity": num(r["Severity"]),
             "hexes": num(r["Hexes"]), "duration": num(r["Duration"]), "chancePerDegree": num(r["ChanceIncreasePerDegree"]),
             "frequency": {}, "damage": [], "fertility": []}
        if kind == "NUCLEAR":
            e["minTurnAtRisk"] = num(r["MinTurnAtRisk"])
        if r["NaturalWonder"]:
            feature = NATURAL_WONDER_EVENT_FEATURES.get(r["NaturalWonder"], r["NaturalWonder"])
            e["id"] += "_" + feature[len("FEATURE_"):]
            e["naturalWonder"] = feature
            wonder_events.append(e)
        else:
            events.append(e)
        slot.append(e)

    def runs(rows):
        """(the event row a table row belongs to, the row): the k-th run of a name's rows is its k-th event row."""
        count, last = {}, None
        for r in rows:
            if r["Event"] != last:
                count[r["Event"]] = count.get(r["Event"], -1) + 1
                last = r["Event"]
            slot = variants.get(r["Event"], [])
            yield (slot[count[r["Event"]]] if count[r["Event"]] < len(slot) else None), r

    # Frequencies list every event once per intensity, so there the k-th row of a name and intensity is its k-th event row.
    seen = {}
    for r in table(path, "Event frequencies by disaster intensity"):
        key = (r["Event"], r["Realism setting"])
        k = seen.get(key, 0)
        seen[key] = k + 1
        slot = variants.get(r["Event"], [])
        e = slot[k] if k < len(slot) else None
        if e:
            e["frequency"][r["Realism setting"].upper()] = num(r["Occurrences per game"])
    damage = {}
    for e, r in runs(table(path, "Event damage")):
        if not e:
            continue
        if r["Damage type"] == "radiation leaked":
            e["fallout"] = num(r["Fallout turns"])  # nuclear accidents (09)
        damage.setdefault(e["id"], {})[r["Damage type"]] = {"type": snake(r["Damage type"]), "percent": num(r["%"]),
                                                             "minHp": num(r["Min HP"]), "maxHp": num(r["Max HP"])}
    fert = {}
    for e, r in runs(table(path, "Event yield changes (fertility)")):
        if not e:
            continue
        key = (r["Yield"], r["Feature"])
        fert.setdefault(e["id"], {})[key] = {"yield": YIELD_WORDS.get(r["Yield"], r["Yield"].upper()),
                                              "feature": "" if e["kind"] in storm_kinds else FEATURE_IDS[r["Feature"]],
                                              "percent": num(r["% of tiles"]), "amount": num(r["Amount"]),
                                              "replaceFeature": r["Replace feature"] == "1"}
    for e in events + wonder_events:
        e["damage"] = list(damage.get(e["id"], {}).values())
        e["fertility"] = list(fert.get(e["id"], {}).values())
    intensities = [{"id": "DISASTERS_" + r["Setting"].upper(), "name": r["Setting"], "activeVolcanoes": num(r["% volcanoes active"]),
                    "extraRange": num(r["Extra range"])} for r in table(path, "Disaster intensity settings")]
    return {"disasters": events + wonder_events, "climatePhases": phases, "disasterIntensities": intensities}


