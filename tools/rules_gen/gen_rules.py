def gen_policies():
    ids = node_names()
    pids = policy_refs()
    # Cards with hand-written modifiers keep them (Ancient and Classical cards, Dark Age cards).
    handwritten = {m["source"] for m in json.loads((OUT / "modifiers.json").read_text(encoding="utf-8"))["modifiers"]}
    govs = {r["Government"]: "GOVERNMENT_" + snake(r["Government"])
            for r in table(SPEC / "governments-policies.md", "Governments")}
    policy_ids = {}
    for section in ("Military policies", "Economic policies", "Diplomatic policies", "Wildcard policies",
                    "Great Person policies"):
        for row in table(SPEC / "governments-policies.md", section):
            policy_ids[row["Policy"]] = "POLICY_" + snake(row["Policy"])
    out = []
    for section, slot in (("Military policies", "MILITARY"), ("Economic policies", "ECONOMIC"),
                          ("Diplomatic policies", "DIPLOMATIC"), ("Wildcard policies", "WILDCARD"),
                          ("Great Person policies", "GREAT_PERSON")):
        for row in table(SPEC / "governments-policies.md", section):
            p = {"id": "POLICY_" + snake(row["Policy"]), "name": row["Policy"], "slot": slot}
            if row["Unlock"] in ids:
                p["unlock"] = ids[row["Unlock"]]
            elif row["Unlock"] == "government":
                p["legacy"] = True  # legacy cards arrive with eras and legacy rules
            # A card goes obsolete once any of its replacement cards is unlocked.
            obsolete = [policy_ids[x.strip()] for x in row["Obsoleted by"].split(",") if x.strip()]
            if obsolete:
                p["obsoletedBy"] = obsolete
            # Dark Age cards [R&F]: only in a Dark Age, while the world is in their era window (09: Ages).
            age = re.fullmatch(r"Dark Age (\w+) Era-(\w+) Era", row["Age requirement [R&F]"] or "")
            if age:
                p["darkAge"] = True
                p["eras"] = ["ERA_" + age.group(1).upper(), "ERA_" + age.group(2).upper()]
            elif row["Age requirement [R&F]"]:
                p["ageRequirement"] = row["Age requirement [R&F]"]
            if row["Government-exclusive [GS]"]:
                p["government"] = govs[row["Government-exclusive [GS]"]]
            if p["id"] not in handwritten:
                mods, untracked = policy_modifiers(p["id"], row["Effects"], pids)
                if mods:
                    p["modifiers"] = mods
                if untracked:
                    p["untrackedEffects"] = untracked
            out.append(p)
    return {"policies": out}


