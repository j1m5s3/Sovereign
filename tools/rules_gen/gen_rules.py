    emitted = {"DISTRICT_" + snake(n) for n in names}
    charge = {row["District"]: row for row in table(SPEC / "districts.md", "Districts that copy adjacency into other yields / build-charge production")}
    out = []
    for name in names:
        row = stats[name]
        d = {"id": "DISTRICT_" + snake(name), "name": name}
        if row["HP"]:
            d["hp"] = num(row["HP"])
        m = re.search(r"attack range (\d+)", row["Placement/flags"])
        if m:
            d["attackRange"] = int(m.group(1))
        if row["Air slots"]:
            d["airSlots"] = num(row["Air slots"])  # aircraft based here (City Center 1, Aerodrome 2)
        if plunder(row["Pillage"]):
            d["plunder"] = plunder(row["Pillage"])  # 05: Pillage
        if row["Specialist yields"]:
            d["specialistYields"] = yields(row["Specialist yields"])  # each specialist's yields (02)
        if name != "City Center":
            d["unlock"] = unlock_id(row["Unlock"])
            d["cost"] = num(row["Base cost"])
            model, param = row["Cost progression"].split()
            d["costProgression"] = model
            d["costDiscountPercent"] = num(param) if model == "NUM_UNDER_AVG_PLUS_TECH" else 0
            d["needsPopulation"] = row["Needs pop"] == "yes"
            d["maintenance"] = num(row["Maintenance"])
            if "not adjacent to City Center" in row["Placement/flags"]:
                d["notAdjacentToCityCenter"] = True
            if "coast/lake" in row["Placement/flags"]:
                d["water"] = True  # on Coast or Lake next to land
            d["adjacency"] = district_adjacency(extra[name]["Adjacency rules"], emitted)
            points = gpp(row["GPP per turn"])
            if points:
                d["greatPersonPoints"] = points
            flags = row["Placement/flags"]
            if row["Housing"]:
                d["housing"] = num(row["Housing"])
            if row["Amenity"]:
                d["amenities"] = num(row["Amenity"])
            mods = extra[name]["Modifiers"] or ""
            m = re.search(r"\+(\d+) Amenity where district is [\w ]+ and adjacent to ([^;]+)", mods)
