STRATEGIC_RESOURCES = {"Horses", "Iron", "Niter", "Coal", "Oil", "Aluminum", "Uranium"}


def wonder_effect(wid, part, w, modifiers, eras):
    """A wonder's effect the policy parser does not read -> typed effects ([] when it became a
    field or a modifier), or None to leave it to the policy parser."""
    def mod(suffix, collection, effect, args, reqs=None):
        m = {"id": "%s_%s" % (wid, suffix), "source": wid, "collection": collection, "effect": effect, "arguments": args}
        if reqs:
            m["subjectRequirements"] = {"all": reqs}
        modifiers.append(m)
    t = re.sub(r" \(one-time\)$", "", part)
    m = re.fullmatch(r"\+(\d+)% (\w+)", t)
    if m and m.group(2) in YIELD_WORDS:
        mod("CITY_" + YIELD_WORDS[m.group(2)], "OWNER_CITY", "ADJUST_CITY_YIELD_PERCENT", {"yield": YIELD_WORDS[m.group(2)], "amount": int(m.group(1))})
        return []
    m = re.fullmatch(r"\+(\d+) Appeal( in all your cities)?", t)
    if m:
        mod("APPEAL", "PLAYER_CITIES" if m.group(2) else "OWNER_CITY", "ADJUST_CITY_APPEAL", {"amount": int(m.group(1))})
        return []
    m = re.fullmatch(r"\+(\d+) (\w+) per turn", t)
    if m and m.group(2) in STRATEGIC_RESOURCES:
        return [{"kind": "RESOURCE_PER_TURN", "what": "RESOURCE_" + m.group(2).upper(), "amount": int(m.group(1))}]  # while it stands
    m = re.fullmatch(r"\+(\d+) (Military|Economic|Diplomatic|Wildcard) slot", t)
    if m:
        w.setdefault("policySlots", {})[m.group(2).upper()] = int(m.group(1))
        return []
    m = re.fullmatch(r"\+(\d+) spread charge\(s\) for your units", t)
    if m:
        w["spreadCharges"] = int(m.group(1))  # Hagia Sophia: religious units bought or trained
        return []
    m = re.fullmatch(r"\+(\d+)% Production toward (.+?) units of any era in all your cities", t)
    if m and m.group(2) in UNIT_CLASS_WORDS:
        mod("UNITS", "PLAYER_CITIES", "ADJUST_UNIT_PRODUCTION_PERCENT", {"unitClass": UNIT_CLASS_WORDS[m.group(2)], "amount": int(m.group(1))})
        return []
    m = re.fullmatch(r"(.+?) on this city's tiles where tile (?:is|has) (.+?)(?: or tile (?:is|has) (.+?))?(?: in all cities where city has .+| in all cities where (player owns object))?", t)
    if m:
        collection = "PLAYER_CITY_PLOTS" if m.group(4) else "OWNER_CITY_PLOTS"  # Huey Teocalli: the owner's lakes in every city
        gains = [re.fullmatch(r"\+(\d+) (\w+)", g) for g in m.group(1).split(", ")]
        alternatives = []  # each a list of requirements that must all hold
        for place in (m.group(2), m.group(3)):
            k = re.fullmatch(r"(\w+) Class and NOT tile is (.+)", place or "")  # Petra: desert and its hills, not floodplains
            if k and k.group(1) in TERRAIN_BASES and k.group(2) in FEATURE_IDS:
                tid = TERRAIN_BASES[k.group(1)][0]
                for terrain in (tid, tid + "_HILLS"):
                    alternatives.append([{"type": "PLOT_HAS_TERRAIN", "ref": terrain},
                                         {"type": "PLOT_HAS_FEATURE", "ref": FEATURE_IDS[k.group(2)], "negate": True}])
            elif place == "Coast and Lake and NOT tile is a lake":  # Mausoleum: the sea's Coast, not lakes (01: Lake)
                alternatives.append([{"type": "PLOT_HAS_TERRAIN", "ref": "TERRAIN_COAST"}, {"type": "PLOT_IS_LAKE", "negate": True}])
            elif place == "a lake":  # Huey Teocalli
                alternatives.append([{"type": "PLOT_IS_LAKE"}])
            elif place in FEATURE_IDS:
                alternatives.append([{"type": "PLOT_HAS_FEATURE", "ref": FEATURE_IDS[place]}])
            elif place in terrain_names():
                alternatives.append([{"type": "PLOT_HAS_TERRAIN", "ref": terrain_names()[place]}])
            elif place in ("Quarry", "Mine"):  # Ruhr Valley
                alternatives.append([{"type": "PLOT_HAS_IMPROVEMENT", "ref": "IMPROVEMENT_" + snake(place)}])
            elif place is not None:
                return None
        if not all(g and g.group(2) in YIELD_WORDS for g in gains):
            return None
        for g in gains:
            for i, reqs in enumerate(alternatives):  # either place: one modifier each
                mod("PLOTS_%s_%d" % (YIELD_WORDS[g.group(2)], i), collection, "ADJUST_PLOT_YIELD",
                    {"yield": YIELD_WORDS[g.group(2)], "amount": int(g.group(1))}, reqs)
        return []
    # One-time effects on completion.
    m = re.fullmatch(r"grants (\d+) random (technology|civic)", t)
    if m:
        return [{"kind": "RANDOM_TECHS" if m.group(2) == "technology" else "RANDOM_CIVICS", "count": int(m.group(1))}]
    m = re.fullmatch(r"grants (\d+) random Inspiration\(s\) \((\w+ Era) to (\w+ Era)\)", t)
    if m:
        return [{"kind": "RANDOM_BOOST", "tree": "CIVIC", "count": int(m.group(1)), "minEra": eras[m.group(2)], "maxEra": eras[m.group(3)]}]
    m = re.fullmatch(r"\+(\d+) Diplomatic Victory Points", t)
    if m:
        return [{"kind": "DIPLOMATIC_VP", "amount": int(m.group(1))}]
    m = re.fullmatch(r"\+(\d+) Governor Title\(s\)", t)
    if m:
        return [{"kind": "GOVERNOR_TITLES", "amount": int(m.group(1))}]
    m = re.fullmatch(r"\+(\d+) Population in all your cities", t)
    if m:
        return [{"kind": "POPULATION", "amount": int(m.group(1))}]
    if t == "grants enough XP for a promotion for your units":
        return [{"kind": "PROMOTE_ALL"}]
    m = re.fullmatch(r"multiplies treasury by (\d+)", t)
    if m:
        return [{"kind": "TREASURY_PERCENT", "amount": int(m.group(1))}]
    return None


CS_SUFFIX = " for all players where is suzerain and player is at peace and player is suzerain bonus enabled"


def cs_modifiers(cid, text, ids):
    """A city-state's suzerain bonus -> modifiers (source = the city-state; the core applies them to its
    suzerain at peace with it). City-state forms first, then the policy card parser."""
    mods, rest = [], []

    def add(collection, effect, args, reqs=None):
        m = {"id": "%s_S%d" % (cid, len(mods) + 1), "source": cid, "collection": collection, "effect": effect, "arguments": args}
        if reqs:
            m["subjectRequirements"] = {"all": reqs}
        mods.append(m)

    eras = {e: i for i, e in enumerate(ERAS)}
    for t in [p.strip() for p in text.replace(CS_SUFFIX, "").split(";") if p.strip()]:
        m = re.fullmatch(r"adjust wonder production \(Amount=(\d+)\) in all your cities", t)
        if m:
            add("PLAYER_CITIES", "ADJUST_ITEM_PRODUCTION_PERCENT", {"scope": "WONDERS", "amount": int(m.group(1))})
            continue
        m = re.fullmatch(r"\+(\d+)% Production toward projects in all your cities", t)
        if m:
            add("PLAYER_CITIES", "ADJUST_ITEM_PRODUCTION_PERCENT", {"scope": "PROJECTS", "amount": int(m.group(1))})
            continue
        m = re.fullmatch(r"\+(\d+)% (\w+) in all your cities where player is at peace with all majors", t)
        if m and m.group(2) in YIELD_WORDS:
            add("PLAYER_CITIES", "ADJUST_CITY_YIELD_PERCENT", {"yield": YIELD_WORDS[m.group(2)], "amount": int(m.group(1))}, [{"type": "PLAYER_AT_PEACE"}])
            continue
        m = re.fullmatch(r"\+(\d+) (\w+) on your tiles where tile is Coast and Lake(?: and player era at least \(EraType=(\w+) Era\))?", t)
        if m and m.group(2) in YIELD_WORDS:
            reqs = [{"type": "PLOT_HAS_TERRAIN", "ref": "TERRAIN_COAST"}]
            if m.group(3):
                reqs.append({"type": "WORLD_MIN_ERA", "value": eras[m.group(3)]})
            add("PLAYER_CITY_PLOTS", "ADJUST_PLOT_YIELD", {"yield": YIELD_WORDS[m.group(2)], "amount": int(m.group(1))}, reqs)
            continue
        m = re.fullmatch(r"\+(\d+)% (\w+) in all your cities where city has improved (\w+)", t)
        if m and m.group(2) in YIELD_WORDS:
            add("PLAYER_CITIES", "ADJUST_CITY_YIELD_PERCENT", {"yield": YIELD_WORDS[m.group(2)], "amount": int(m.group(1))},
                [{"type": "CITY_HAS_IMPROVED_RESOURCE", "ref": "RESOURCE_" + m.group(3).upper()}])
            continue
        m = re.fullmatch(r"adjust city amenities from city states \(Amount=(\d+)\) in all your cities where city has (.+)", t)
        if m and m.group(2) in ids["districts"]:
            add("PLAYER_CITIES", "ADJUST_CITY_AMENITIES", {"amount": int(m.group(1))}, [{"type": "CITY_HAS_DISTRICT", "ref": ids["districts"][m.group(2)]}])
            continue
        rest.append(t)
    more, untracked = policy_modifiers(cid, "; ".join(rest), ids)
    return mods + more, untracked


def gen_city_states():
    """City-states by type and the envoy tier bonuses each type gives (08: City-States)."""
    states = [{"id": "CITYSTATE_" + snake(r["City-state"]), "name": r["City-state"], "type": r["Type"].upper(),
               "suzerainText": re.sub(r"\*\*[^*]+\*\*: ", "", r["Suzerain bonus"])}
              for r in table(SPEC / "city-states.md", "City-states and suzerain bonuses")]
    refs = policy_refs()
    for st in states:
        if st["id"] == "CITYSTATE_CARDIFF":
            continue  # its free power is read in code (09: Power)
        mods, _ = cs_modifiers(st["id"], st["suzerainText"], refs)
        if mods:
            st["modifiers"] = mods
    buildings = {r["Building"]: "BUILDING_" + snake(r["Building"]) for r in table(SPEC / "buildings.md", "Buildings") if not r.get("Unique to")}
    tiers = []
    for r in table(SPEC / "city-states.md", "Envoy tier bonuses by city-state type"):
        t = r["Effect"]
        m = re.search(r"at least (\d+) Envoys", t)
        if not m:
            continue
        need = int(m.group(1))
        base = {"id": r["Modifier"], "type": r["Type"].upper(), "envoys": need}
        mm = re.match(r"\+(\d+) (\w+) in your capital", t)
        if mm and mm.group(2) in YIELD_WORDS:
            tiers.append({**base, "yield": YIELD_WORDS[mm.group(2)], "amount": int(mm.group(1)), "capital": True})
            continue
        mm = re.match(r"\+(\d+) (\w+) from (.+?) in all your cities", t)
        if mm and mm.group(2) in YIELD_WORDS and mm.group(3) in buildings:
            tiers.append({**base, "yield": YIELD_WORDS[mm.group(2)], "amount": int(mm.group(1)), "building": buildings[mm.group(3)]})
            continue
        # Production toward an item kind: in the capital, or in cities with one of the buildings.
        mm = re.match(r"\+(\d+)% Production toward (units|buildings|districts) in (your capital|all your cities where (.+?)) for all players", t)
        if mm:
            row = {**base, "production": int(mm.group(1)), "toward": mm.group(2).upper()}
            if mm.group(3) == "your capital":
                row["capital"] = True
            else:
                names = re.findall(r"city has ([A-Z][\w' ]+?)(?= or | for |$)", mm.group(4))
                refs = [buildings[n] for n in names if n in buildings]
                if not refs:
                    continue
                row["buildings"] = refs
            tiers.append(row)
    return {"cityStates": states, "envoyBonuses": tiers}


BELIEF_CLASSES = ["Pantheon", "Follower", "Worship", "Founder", "Enhancer"]


def gen_religion():
    """Beliefs by class, the religions to found and the per-size limit (06-religion.md).
    Belief effects the core applies are hand-written modifiers (modifiers.json, source BELIEF_*);
    the text here is what the player reads."""
    buildings = {r["Building"]: "BUILDING_" + snake(r["Building"]) for r in table(SPEC / "buildings.md", "Buildings") if not r.get("Unique to")}
    units = {r["Unit"]: "UNIT_" + snake(r["Unit"]) for r in table(SPEC / "units.md", "Units") if not r.get("Unique to")}
    beliefs = []
    for cls in BELIEF_CLASSES:
        for row in table(SPEC / "religion.md", cls):
            b = {"id": "BELIEF_" + snake(row["Belief"]), "name": row["Belief"], "class": cls.upper(), "text": row["Effects"]}
            m = re.fullmatch(r"unlocks worship building (.+)", row["Effects"])
            if m and m.group(1) in buildings:
                b["worshipBuilding"] = buildings[m.group(1)]
            m = re.search(r"grants 1 (\w+) in your capital", row["Effects"])
            if m and m.group(1) in units:
                b["grantUnit"] = units[m.group(1)]
            beliefs.append(b)
    religions = [{"id": "RELIGION_" + snake(r["Religion"]), "name": r["Religion"]}
                 for r in table(SPEC / "religion.md", "Religions") if r["Religion"] not in ("Pantheon", "Custom Religion")]
    return {"beliefs": beliefs, "religions": religions}


