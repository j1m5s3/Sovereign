#!/usr/bin/env python3
"""Generate the rules core's baseline JSON data from the Civ VI reference tables.

Reads specs/civ6/data/*.md (themselves generated by tools/civ6_extract) and
writes data/rules/{globals,terrain,resources,promotions,units,districts,barbarians,buildings,techs,civics,
governments,policies,improvements}.json. Sovereign's own choices live in hand-written files
beside them (civilizations.json, setup.json, modifiers.json) or in later rules
layers, never in the generated files.

Usage (from the repo root):  python3 tools/rules_gen/gen_rules.py
Check mode for CI:            python3 tools/rules_gen/gen_rules.py --check
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "specs" / "civ6" / "data"
OUT = ROOT / "data" / "rules"

YIELD_WORDS = {
    "Food": "FOOD", "Production": "PRODUCTION", "Gold": "GOLD",
    "Science": "SCIENCE", "Culture": "CULTURE", "Faith": "FAITH",
}

# Terrain display names -> (id, climate base, relief). The tables list one
# "Mountain" row per climate in order, so mountains are named from the row
# above them.
TERRAIN_BASES = {
    "Grassland": ("TERRAIN_GRASS", "GRASSLAND"),
    "Plains": ("TERRAIN_PLAINS", "PLAINS"),
    "Desert": ("TERRAIN_DESERT", "DESERT"),
    "Tundra": ("TERRAIN_TUNDRA", "TUNDRA"),
    "Snow": ("TERRAIN_SNOW", "SNOW"),
    "Coast and Lake": ("TERRAIN_COAST", "COAST"),
    "Ocean": ("TERRAIN_OCEAN", "OCEAN"),
}

FEATURE_IDS = {
    "Desert Floodplains": "FEATURE_FLOODPLAINS",
    "Ice": "FEATURE_ICE",
    "Rainforest": "FEATURE_JUNGLE",
    "Woods": "FEATURE_FOREST",
    "Oasis": "FEATURE_OASIS",
    "Marsh": "FEATURE_MARSH",
    "Reef": "FEATURE_REEF",
    "Grassland Floodplains": "FEATURE_FLOODPLAINS_GRASSLAND",
    "Plains Floodplains": "FEATURE_FLOODPLAINS_PLAINS",
    "Geothermal Fissure": "FEATURE_GEOTHERMAL_FISSURE",
    "Volcano": "FEATURE_VOLCANO",
    "Volcanic Soil": "FEATURE_VOLCANIC_SOIL",
    "Burning Woods": "FEATURE_BURNING_FOREST",
    "Burnt Woods": "FEATURE_BURNT_FOREST",
    "Burning Rainforest": "FEATURE_BURNING_JUNGLE",
    "Burnt Rainforest": "FEATURE_BURNT_JUNGLE",
}
# Features the engine treats as impassable although the table has no column for it.
IMPASSABLE_FEATURES = {"FEATURE_ICE", "FEATURE_VOLCANO"}


def tables(path):
    """Yield (section heading, header cells, rows) for each table in a generated file."""
    section, header, rows = None, None, []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            if header:
                yield section, header, rows
            section, header, rows = line[3:].strip(), None, []
        elif line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if header is None:
                header = cells
            elif set("".join(cells)) <= set("-: "):
                continue
            else:
                rows.append(dict(zip(header, cells)))
    if header:
        yield section, header, rows


def table(path, section):
    for sec, _, rows in tables(path):
        if sec == section:
            return rows
    raise SystemExit(f"{path.name}: section '{section}' not found")


def num(text, default=0):
    text = (text or "").strip()
    if not text:
        return default
    m = re.fullmatch(r"-?\d+(\.\d+)?", text)
    if not m:
        raise ValueError(f"not a number: {text!r}")
    return float(text) if "." in text else int(text)


def yields(text):
    out = {}
    for part in filter(None, (p.strip() for p in (text or "").split(","))):
        m = re.fullmatch(r"([+-]?\d+(?:\.\d+)?) (\w+)", part)
        if not m or m.group(2) not in YIELD_WORDS:
            raise ValueError(f"bad yield {part!r}")
        out[YIELD_WORDS[m.group(2)]] = num(m.group(1).lstrip("+"))
    return out


def snake(name):
    return re.sub(r"[^A-Z0-9]+", "_", name.upper()).strip("_")


def terrain_names():
    """Map every display name used in Valid-terrain columns to an id."""
    names = {}
    for disp, (tid, _) in TERRAIN_BASES.items():
        names[disp] = tid
        names[f"{disp} (Hills)"] = tid + "_HILLS"
    return names


def gen_terrain():
    terrains = []
    last_base = None
    for row in table(SPEC / "terrain-features-resources.md", "Terrains"):
        disp = row["Terrain"]
        hills_flag, mountain_flag = (row["Hills/Mountain"].split("/") + [""])[:2]
        if disp == "Mountain":
            tid, base = TERRAIN_BASES[last_base]
            tid += "_MOUNTAIN"
            relief = "MOUNTAIN"
            name = f"{last_base} Mountain"
        elif hills_flag.strip() == "yes":
            plain = disp.replace(" (Hills)", "")
            tid, base = TERRAIN_BASES[plain]
            tid += "_HILLS"
            relief = "HILLS"
            name = disp
        else:
            tid, base = TERRAIN_BASES[disp]
            relief = "FLAT"
            name = disp
            last_base = disp
        sight_mod, sight_through = (row["Sight mod / through"].split("/") + ["0"])[:2]
        water, shallow = (row["Water/shallow"].split("/") + [""])[:2]
        t = {
            "id": tid, "name": name, "base": base, "relief": relief,
            "yields": yields(row["Yields"]),
            "moveCost": num(row["Move cost"], 1),
            "defense": num(row["Defense"]),
            "appeal": num(row["Appeal"]),
            "sightModifier": num(sight_mod),
            "sightThrough": num(sight_through),
        }
        if row["Impassable"] == "yes":
            t["impassable"] = True
        if water.strip() == "yes":
            t["water"] = True
        if shallow.strip() == "yes":
            t["shallowWater"] = True
        terrains.append(t)

    tnames = terrain_names()
    features = []
    for row in table(SPEC / "terrain-features-resources.md", "Features"):
        fid = FEATURE_IDS[row["Feature"]]
        valid = []
        for v in (x.strip() for x in row["Valid terrains"].split(",")):
            if v == "Mountain":
                continue  # volcanoes: every mountain, added below
            if v and tnames[v] not in valid:
                valid.append(tnames[v])
        if row["Feature"] == "Volcano":
            valid = [t["id"] for t in terrains if t["relief"] == "MOUNTAIN"]
        f = {
            "id": fid, "name": row["Feature"],
            "yields": yields(row["Yields"]),
            "moveChange": num(row["Move change"]),
            "defense": num(row["Defense"]),
            "appeal": num(row["Appeal"]),
            "sightThrough": num(row["Sight-blocking"]),
            "validTerrains": valid,
        }
        if row["Removable / remove tech"].startswith("yes"):
            f["removable"] = True
            tech = row["Removable / remove tech"][3:].strip()
            if tech:
                f["removeTech"] = unlock_id(tech)
        harvest = harvest_yields(row["Harvest yields"])
        if harvest:
            f["harvestYields"] = harvest
        if row["Fresh water"] == "yes":
            f["freshWater"] = True
        if fid in IMPASSABLE_FEATURES:
            f["impassable"] = True
        features.append(f)
    # Natural wonders (01: Natural wonders), features the map script places in clusters.
    mountains = [t["id"] for t in terrains if t["relief"] == "MOUNTAIN"]
    for row in table(SPEC / "terrain-features-resources.md", "Natural wonders"):
        valid = []
        for v in (x.strip() for x in row["Valid terrains"].split(",")):
            for tid in (mountains if v == "Mountain" else [tnames[v]] if v in tnames else []):
                if tid not in valid:
                    valid.append(tid)
        f = {"id": "FEATURE_" + snake(row["Natural wonder"].replace("á", "a").replace("ạ", "a").replace("ö", "o").replace("ï", "i").replace("ö", "o")),
             "name": row["Natural wonder"], "naturalWonder": True, "tiles": num(row["Tiles"]),
             "yields": yields(row["Yields"]), "adjacentYields": yields(row["Adjacent tile yields"]),
             "appeal": num(row["Appeal"]), "validTerrains": valid}
        if row["Impassable"] == "yes":
            f["impassable"] = True
        if row["Doubles adjacent terrain yield"] == "yes":
            f["doublesAdjacentTerrain"] = True
        if row["Fresh water"] == "yes":
            f["freshWater"] = True
        features.append(f)
    # Roads by era, and the railroad Military Engineers lay (01: Routes).
    routes = []
    for row in table(SPEC / "terrain-features-resources.md", "Routes"):
        r = {"id": "ROUTE_" + snake(row["Route"]), "name": row["Route"], "moveCost": float(row["Movement cost"])}
        if row["Only built by unit"]:
            r["unitOnly"] = True
            if row["Prereq tech [GS]"]:
                r["tech"] = "TECH_" + snake(row["Prereq tech [GS]"])
            costs = {}
            for part in [x.strip() for x in row["Resource cost"].split(",") if x.strip()]:
                m = re.fullmatch(r"(\w+) x(\d+)", part)
                if m:
                    costs["RESOURCE_" + snake(m.group(1))] = int(m.group(2))
            if costs:
                r["resourceCost"] = costs
        if row["Bridges"] == "yes":
            r["bridges"] = True
        if row["Prereq era"]:
            r["era"] = "ERA_" + row["Prereq era"].replace(" Era", "").upper()
        routes.append(r)
    return {"terrains": terrains, "features": features, "routes": routes}


def harvest_yields(text):
    """'Production 10, Food 10' or '20 Food' -> {"PRODUCTION": 10, "FOOD": 10}."""
    out = {}
    for part in filter(None, (p.strip() for p in (text or "").split(","))):
        m = re.fullmatch(r"(\w+) (\d+)", part) or re.fullmatch(r"(\d+) (\w+)", part)
        a, b = m.group(1), m.group(2)
        word, amount = (a, b) if a in YIELD_WORDS else (b, a)
        out[YIELD_WORDS[word]] = int(amount)
    return out


def gen_resources():
    tnames = terrain_names()
    accumulation = {r["Resource"]: r for r in table(SPEC / "terrain-features-resources.md",
                                                    "Strategic resource accumulation and power [GS]")}
    fnames = FEATURE_IDS
    out = []
    for section, cls in (("Bonus resources", "BONUS"), ("Luxury resources", "LUXURY"),
                         ("Strategic resources", "STRATEGIC")):
        for row in table(SPEC / "terrain-features-resources.md", section):
            land, sea = (row["Frequency/sea"].split("/") + ["0"])[:2]
            terr, feat = [], []
            for v in (x.strip() for x in row["Valid terrain/feature"].split(",")):
                if not v:
                    continue
                if v in tnames:
                    terr.append(tnames[v])
                elif v in fnames:
                    feat.append(fnames[v])
                else:
                    raise ValueError(f"resource {row['Resource']}: unknown place {v!r}")
            r = {
                "id": "RESOURCE_" + snake(row["Resource"]), "name": row["Resource"], "class": cls,
                "yields": yields(row["Yields"]),
                "frequency": num(land), "seaFrequency": num(sea),
                "validTerrains": terr, "validFeatures": feat,
            }
            if row["Revealed by"]:
                r["revealTech"] = "TECH_" + snake(row["Revealed by"])
            if cls == "LUXURY" and row["Amenities"]:
                r["amenityCities"] = num(row["Amenities"])  # +1 amenity to this many cities
            m = re.fullmatch(r"(.+) \((.+)\)", row["Harvest"])
            if m:
                r["harvestYields"] = harvest_yields(m.group(1))
                r["harvestTech"] = unlock_id(m.group(2))
            if row["Resource"] in accumulation:
                acc = accumulation[row["Resource"]]
                r["accumulation"] = num(acc["Base / improved extraction per turn"].split("/")[1])
                r["stockpileCap"] = num(acc["Stockpile cap"])
            out.append(r)
    return {"resources": out}


def gen_units():
    out, city_state_units = [], []
    # City-states' units (08: Lahore's Nihang) are kept, after the others: whoever enjoys the city-state's suzerain bonus
    # buys them.
    city_states = {r["City-state"]: "CITYSTATE_" + snake(r["City-state"]) for r in table(SPEC / "city-states.md", "City-states and suzerain bonuses")}
    ability_tags = {r["Ability"]: [t.strip().upper() for t in r["Applies to class tags"].split(",") if t.strip()]
                    for r in table(SPEC / "units.md", "Unit abilities")}
    for row in table(SPEC / "units.md", "Units"):
        city_state = city_states.get(row.get("Unique to") or "")
        if row.get("Unique to") and not city_state:
            continue  # Sovereign defines its own uniques (leaders-and-art-style.md)
        cls = row["Class"]
        special = row["Special"]
        layer = "CIVILIAN" if cls == "civilian" else "SUPPORT" if cls == "Support" else "MILITARY"
        combat = num(row["CS"])
        u = {
            "id": "UNIT_" + snake(row["Unit"]), "name": row["Unit"],
            "class": snake(cls), "domain": row["Domain"].upper(), "layer": layer,
            "cost": num(row["Cost"]), "maintenance": num(row["Gold maint."]),
            "combat": combat, "ranged": num(row["RS"]), "range": num(row["Range"]),
            "moves": num(row["Moves"], 0), "sight": num(row["Sight"], 2),
        }
        if combat > 0 and "no ZOC" not in special and row["Domain"] != "Air":
            u["zoneOfControl"] = True
        if row["Unit"] == "Archaeologist":
            u["excavations"] = 3  # 07: Archaeology (the Archaeologist's three digs; not in the extracted table)
        if row["Unit"] == "Aircraft Carrier":
            u["airSlots"] = 2  # 05: Naval carrier, 2 air slots (more with promotions)
        if cls == "Air Bomber" or row["Unit"] == "Nuclear Submarine":
            u["deliversWmd"] = True  # 05: Nuclear weapons, delivery
        if "Unit Wmd Resistance" in (row["Innate abilities (via class tags)"] or ""):
            u["wmdImmune"] = True
        if num(row["Anti-air"]):
            u["antiAir"] = num(row["Anti-air"])  # protects adjacent plots from aircraft (05: air combat)
        if "found city" in special:
            u["foundCity"] = True
        m = re.search(r"charges (\d+)", special)
        if m and "heal charges" not in special:
            u["buildCharges"] = int(m.group(1))
        if row["Unit"] == "Military Engineer":
            u["buildsRoads"] = True  # 01: Routes, a road by hand for a charge (until railroads [GS])
        prog = row["Cost progression"].split()
        if len(prog) == 2 and prog[0] == "PREVIOUS_COPIES":
            u["costProgression"] = int(prog[1])
        if len(prog) == 2 and prog[0] == "GAME_PROGRESS":
            u["gameProgressPercent"] = int(prog[1])  # the Trader, Lahore's Nihang
        m = re.search(r"pop cost (\d+)", special)
        if m:
            u["popCost"] = int(m.group(1))
        m = re.search(r"needs pop (\d+)", special)
        if m:
            u["minPopulation"] = int(m.group(1))
        if "must purchase" in special:
            u["mustPurchase"] = True
        # Great People (cost 1, never bought) come from great person points, not a city queue.
        if num(row["Cost"]) <= 1 and not row["Purchase"]:
            u["trainable"] = False
        # Spies are off-map agents within the spy capacity civics grant; the first comes with
        # Diplomatic Service (08: Espionage).
        if special == "spy":
            u["agent"] = True
            u["spy"] = True
            u["unlock"] = "CIVIC_DIPLOMATIC_SERVICE"
        # "needs Temple" / "needs Prasat/Stave Church/Temple": any one of the buildings in the
        # city (unique buildings Sovereign does not have are dropped).
        m = re.search(r"needs (?!pop )(.+?)(?= must purchase|$)", special)
        if m:
            known = {r["Building"] for r in table(SPEC / "buildings.md", "Buildings") if not r.get("Unique to")}
            need = ["BUILDING_" + snake(b) for b in m.group(1).split("/") if b in known]
            if need:
                u["needsBuilding"] = need
        if row["Purchase"]:
            u["purchaseYield"] = row["Purchase"].upper()
        # Religious units (06: Religious units): strength in theological combat, spread charges,
        # the share of other religions a spread removes, heal charges.
        m = re.search(r"religious str (\d+)", special)
        if m:
            u["religiousStrength"] = int(m.group(1))
        m = re.search(r"spread (\d+)", special)
        if m:
            u["spreadCharges"] = int(m.group(1))
        m = re.search(r"evict (\d+)%", special)
        if m:
            u["evictPercent"] = int(m.group(1))
        m = re.search(r"heal charges (\d+)", special)
        if m:
            u["healCharges"] = int(m.group(1))
        if special == "found religion":
            u["foundReligion"] = True
        if row["Unlock"]:
            u["unlock"] = unlock_id(row["Unlock"])
        m = re.fullmatch(r"(\w+) (\d+)", row["Strategic cost [GS]"])
        if m:
            u["strategicCost"] = {"resource": "RESOURCE_" + snake(m.group(1)), "amount": int(m.group(2))}
        if row["Upgrades to"]:
            u["upgradesTo"] = "UNIT_" + snake(row["Upgrades to"])
        if row["Forced obsolete"]:
            u["obsoleteWith"] = unlock_id(row["Forced obsolete"])
        if num(row["Bombard"]):
            u["bombard"] = num(row["Bombard"])
        m = re.fullmatch(r"(\d+) (\w+)/turn", row["Resource maint. [GS]"])
        if m:
            u["resourceMaintenance"] = {"resource": "RESOURCE_" + snake(m.group(2)), "amount": int(m.group(1))}
        if snake(cls) in promotion_classes():
            u["promotionClass"] = "PROMOTION_CLASS_" + snake(cls)
        abilities = [a.strip() for a in row["Innate abilities (via class tags)"].split(",") if a.strip()]
        if abilities:
            u["abilities"] = ["ABILITY_" + snake(a) for a in abilities]
        if city_state:
            u["cityState"] = city_state
            # It fights as the class its innate abilities name (the Nihang's Anti-Spear: melee), and carries a tag of its
            # own (lahore_nihang) that the abilities its suzerain's buildings grant name.
            innate = {t for a in abilities for t in ability_tags.get(a, [])}
            if len(innate) == 1:
                u["class"] = innate.pop()
            own = snake(row["Unique to"]) + "_" + snake(row["Unit"])
            if any(own in tags for tags in ability_tags.values()):
                u["tags"] = [own]
            city_state_units.append(u)
        else:
            out.append(u)
    out += city_state_units
    known = {u["id"] for u in out}
    for u in out:
        if u.get("upgradesTo") not in known:
            u.pop("upgradesTo", None)  # upgrades into a unique unit
    for row in table(SPEC / "units.md", "Unit capture results"):
        for u in out:
            if u["name"] == row["Captured"]:
                u["capturedAs"] = "UNIT_" + snake(row["Becomes"])
    # Rock Band concert outcomes [GS] (07: Rock Bands; data: Unit_RockbandResults_XP2).
    results = []
    for r in table(SPEC / "units.md", "Rock Band results [GS]"):
        results.append({"id": "ROCKBAND_RESULT_" + snake(r["Result"]), "name": r["Result"], "albumSales": num(r["Album sales"]),
                        "tourismBomb": num(r["Tourism bomb"]), "dies": r["Dies"] == "yes", "gainsLevel": r["Gains level"] == "yes",
                        "extraPromotion": r["Extra promotion"] == "yes",
                        "probability": num(r["Base probability"])})
    return {"units": out, "rockBandResults": results}


