def band_effect(part):
    m = (re.fullmatch(r"\+(\d+) Rock Band level (?:when performing )?at (.+)", part) or
         re.fullmatch(r"adjust unit rock band level (national park|natural wonder) \(Amount=(\d+)\)", part))
    if m:
        amount, place = (m.group(1), m.group(2)) if part.startswith("+") else (m.group(2), m.group(1))
        return {"kind": "BAND_LEVEL", "amount": int(amount), "at": BAND_PLACES[place]} if place in BAND_PLACES else {"kind": "UNTRACKED", "text": part}
    m = (re.fullmatch(r"\+(\d+) Tourism burst at (.+)", part) or
         re.fullmatch(r"adjust unit tourism bomb (national park|natural wonder) \(Amount=(\d+)\)", part))
    if m:
        amount, place = (m.group(1), m.group(2)) if part.startswith("+") else (m.group(2), m.group(1))
        return {"kind": "BAND_BURST", "amount": int(amount), "at": BAND_PLACES[place]} if place in BAND_PLACES else {"kind": "UNTRACKED", "text": part}
    return None


def unit_effects(text):
    """Effect text of a promotion or ability -> list of effect objects. Conditions
    are 'A and B or C' = A and (B or C): a list of any-of groups that must all hold."""
    out = []
    for part in filter(None, (p.strip() for p in text.split("; "))):
        m = re.fullmatch(r"([+-]\d+) Combat Strength(?: in combat(?: where (.*))?)?", part)
        # Inquisition [R&F]: read "friendly territory" as the unit's own territory.
        territory = re.fullmatch(r"([+-]\d+) Combat Strength in friendly territory", part)
        if territory:
            out.append({"kind": "STRENGTH", "amount": int(territory.group(1)), "when": [[{"atom": "OWN_TERRITORY"}]]})
            continue
        simple = [
            (r"\+(\d+) Movement", "MOVES"), (r"\+(\d+) range", "RANGE"), (r"\+(\d+) sight", "SIGHT"),
            (r"\+(\d+) attack\(s\) per turn", "ATTACKS"), (r"\+(\d+)% combat XP", "XP_PERCENT"),
            (r"(\d+)% flanking bonus(?: where (?:Land|Sea) unit)?", "FLANKING_PERCENT"), (r"(\d+)% support bonus", "SUPPORT_PERCENT"),
            (r"\+(\d+)% pillage/plunder yields", "PLUNDER_PERCENT"),
            (r"\+(\d+) HP healing \(Neutral\)", "HEAL_NEUTRAL"), (r"\+(\d+) HP healing \(Enemy\)", "HEAL_ENEMY"),
            (r"\+(\d+) air slots", "AIR_SLOTS"),
            (r"\+(\d+) spread charge\(s\)", "SPREAD_CHARGES"), (r"removes (\d+)% of other religions", "EVICT_PERCENT"),
            (r"adjust unit foreign spread modifier \(Amount=(\d+)\)", "FOREIGN_SPREAD_PERCENT"),
            (r"adjust unit natural wonder deferred charges \(Amount=(\d+)\)", "WONDER_CHARGES"),
            (r"\+(\d+) Gold when a unit is trained/bought", "CONVERT_GOLD"),
            (r"\+(\d+) HP healing \(All\) for your units where within tiles", "HEAL_AURA"),
        ]
        flags = {
            "can move after attacking": "MOVE_AFTER_ATTACK", "can attack after moving": "ATTACK_AFTER_MOVE",
            "adjust unit ignore zoc (Ignore=yes)": "IGNORE_ZOC", "adjust unit exert zoc (Exert=yes)": "EXERT_ZOC",
            "no river crossing penalty": "NO_RIVER_PENALTY", "no combat penalty from damage": "NO_WOUNDED_PENALTY",
            "can heal after moving/attacking": "HEAL_AFTER_ACTION", "can enter foreign territory": "IGNORE_BORDERS",
            "Melee units deal full damage to walls": "WALL_FULL_DAMAGE", "Melee units bypass walls": "BYPASS_WALLS",
            "pillaging costs only 1 movement": "CHEAP_PILLAGE",
            "ignores Hills movement costs": "IGNORE_HILLS", "ignores Forest movement costs": "IGNORE_FOREST",
            "ignores All movement costs": "IGNORE_TERRAIN", "no movement cost to embark/disembark": "FREE_EMBARK",
            "sees through features": "SEES_THROUGH_FEATURES", "can coastal raid": "COASTAL_RAID",
            "converts defeated barbarians": "HEATHEN_CONVERSION", "creates a Relic when killed in theological combat": "MARTYR",
            "adjust unit fight while embarked (CanFight=yes)": "FIGHT_EMBARKED",
            "hidden (only visible when adjacent)": "HIDDEN",
        }
        # Abilities with a condition the core reads in code (05): naval units' movement (Great Lighthouse), open ground
        # (Heavy Chariot), range next to an Observation unit (Observation Balloon, Drone).
        special = {
            "+1 Movement for naval units": {"kind": "MOVES", "amount": 1},
            "+1 Movement when starting on open terrain": {"kind": "OPEN_GROUND_MOVES", "amount": 1},
            "+1 range where adjacent to a friendly Observation unit": {"kind": "OBSERVED_RANGE", "amount": 1},
        }
        if part in special:
            out.append(dict(special[part]))
            continue
        kill = re.fullmatch(r"after killing a unit gain (Gold|Faith|Culture) = (\d+)% of its Combat Strength in combat(?: where vs (Sea|Land) units)?", part)
        if kill:
            e = {"kind": "KILL_YIELD", "amount": int(kill.group(2)), "at": YIELD_WORDS[kill.group(1)]}
            if kill.group(3):
                e["when"] = [[{"atom": "VS_DOMAIN", "value": kill.group(3).upper()}]]
            out.append(e)
            continue
        band = band_effect(part)
        if band:
            out.append(band)
            continue
        if m:
            e = {"kind": "STRENGTH", "amount": int(m.group(1))}
            if m.group(2):
                e["when"] = [[condition_atom(o.strip()) for o in g.split(" or ")] for g in m.group(2).split(" and ")]
            out.append(e)
            continue
        for pattern, kind in simple:
            sm = re.fullmatch(pattern, part)
            if sm:
                out.append({"kind": kind, "amount": int(sm.group(1))})
                break
        else:
            out.append({"kind": flags[part]} if part in flags else {"kind": "UNTRACKED", "text": part})
    return out


def gen_promotions():
    promos = []
    for sec, header, rows in tables(SPEC / "promotions.md"):
        if not header or header[0] != "Promotion":
            continue
        for row in rows:
            p = {"id": "PROMOTION_" + snake(row["Promotion"]), "name": row["Promotion"],
                 "class": "PROMOTION_CLASS_" + snake(sec), "tier": num(row["Tier"])}
            req = [x.strip() for x in row["Requires (any)"].split(",") if x.strip()]
            if req:
                p["requires"] = ["PROMOTION_" + snake(x) for x in req]
            p["effects"] = unit_effects(row["Effect"])
            promos.append(p)
    abilities = []
    for row in table(SPEC / "units.md", "Unit abilities"):
        tags = []
        for t in (x.strip().upper() for x in row["Applies to class tags"].split(",") if x.strip()):
            tags += TAG_ALIASES.get(t, [t])
        a = {"id": "ABILITY_" + snake(row["Ability"]), "name": row["Ability"], "classes": tags}
        if row["Inactive by default"]:
            a["inactive"] = True
        a["effects"] = ABILITY_OVERRIDES.get(row["Ability"]) or unit_effects(row["Effects"])
        abilities.append(a)
    return {"promotions": promos, "abilities": abilities}


def gen_buildings():
    # The Spaceport's "rockets" are internal markers of launch art (cost 1, no effect), not buildings.
    rows = [r for r in table(SPEC / "buildings.md", "Buildings") if not r.get("Unique to") and r["District"] != "Spaceport"]
    # Theming bonuses (07: Theming bonuses): "unique person / same object / unique civs / same eras" flags.
    theming = {}
    for r in table(SPEC / "buildings.md", "Great Work slots and theming"):
        flags = r["Theming: unique person / same object / unique civs / same eras"].split("/")
        pct = r["Theming yield x / tourism x"].split("/")
        if any(f.strip() == "yes" for f in flags) and pct[0].strip() not in ("", "0"):
            theming[r["Building"]] = {"uniquePerson": flags[0].strip() == "yes", "sameObject": flags[1].strip() == "yes",
                                      "uniqueCivs": flags[2].strip() == "yes", "sameEra": flags[3].strip() == "yes",
                                      "yieldPercent": int(pct[0]), "tourismPercent": int(pct[1])}
    ids = {r["Building"]: "BUILDING_" + snake(r["Building"]) for r in rows}
    out = []
    for row in rows:
        b = {
            "id": ids[row["Building"]], "name": row["Building"],
            "district": "DISTRICT_" + snake(row["District"]),
            "cost": num(row["Cost"]), "maintenance": num(row["Maint."]),
            "yields": yields(row["Yields"]),
        }
        if row["Unlock"]:
            b["unlock"] = unlock_id(row["Unlock"])
        if row["Housing"]:
            b["housing"] = num(row["Housing"])
        if row["Amenity"]:
            b["amenities"] = num(row["Amenity"])
        if row.get("Regional range") and num(row["Regional range"]):
            b["regionalRange"] = num(row["Regional range"])  # its effects reach the owner's cities this near (03)
        # Specialist slots it opens in its district, and what each specialist there gains (02: Citizens and specialists).
        if row["Citizen slots"] and num(row["Citizen slots"]):
            b["citizenSlots"] = num(row["Citizen slots"])
        if row["Specialist yields"]:
            b["specialistYields"] = yields(row["Specialist yields"])
        m = re.fullmatch(r"(\d+) HP / \+(\d+)", row["Defense"])
        if m:
            b["outerDefenseHp"], b["defense"] = int(m.group(1)), int(m.group(2))
        reqs = [ids[x.strip()] for x in row["Requires"].split(",") if x.strip() in ids]
        if reqs:
            b["requires"] = reqs  # any one of them (BuildingPrereqs): the Armory needs a Barracks or a Stable
        excl = [ids[x.strip()] for x in row["Exclusive with"].split(",") if x.strip() in ids]
        if excl:
            b["exclusiveWith"] = excl  # never in the same city (the Barracks and the Stable, 03)
        m = re.search(r"\+(\d+) air slots", row["Modifiers"] or "")
        if m:
            b["airSlots"] = int(m.group(1))  # Hangar, Airport (05: air units)
        # The ability units trained in its city keep: the Barracks' +25% combat XP for melee, ranged and anti-cavalry (03).
        m = re.search(r"ability ([^\[;]+?) \[\+\d+% combat XP\] for units trained in this city", row["Modifiers"] or "")
        if m:
            b["trainedAbility"] = "ABILITY_" + snake(m.group(1))
        # Power [GS] (09: Power): what it needs, what it gains when powered, what it burns or gives.
        power = row["Power [GS]"] or ""
        m = re.search(r"needs (\d+) power", power)
        if m:
            b["requiredPower"] = int(m.group(1))
            if row["Extra when powered"]:
                b["poweredYields"] = yields(row["Extra when powered"])
            m = re.search(r"\+(\d+) amenity when powered", power)
            if m:
                b["poweredAmenities"] = int(m.group(1))
        m = re.search(r"burns (\w+)", power)
        if m:
            # Power per resource burned (Resource_Consumption.PowerProvided, 09: Power): Coal 4, Oil 4, Uranium 16.
            b["burns"] = {"resource": "RESOURCE_" + m.group(1).upper(), "power": {"Coal": 4, "Oil": 4, "Uranium": 16}[m.group(1)]}
        m = re.search(r"\+(\d+) Power \(Free Power Source", row["Modifiers"] or "")
        if m:
            b["powerProvided"] = int(m.group(1))  # Hydroelectric Dam
        m = re.search(r"each charge completes (\d+)% of a project", row["Modifiers"] or "")
        if m:
            b["projectChargePercent"] = int(m.group(1))  # Royal Society (03): a Builder's charge toward a project
        if row["Placement"] == "river":
            b["needsRiver"] = True
        if row["Purchase"] == "Gold":
            b["purchasable"] = True
        if row["Purchase"] == "Faith":
            b["faithOnly"] = True  # worship buildings: bought with Faith, never built
        m = re.search(r"\+(\d+) strategic resource stockpile cap", row["Modifiers"])
        if m:
            b["stockpileCap"] = int(m.group(1))  # 01: the [GS] stockpile model
        if "melee attacks cannot damage the walls" in row["Modifiers"]:
            b["meleeCannotDamageWalls"] = True
        if "walls cannot be bypassed" in row["Modifiers"]:
            b["wallsCannotBeBypassed"] = True
        points = gpp(row["GPP"])
        if points:
            b["greatPersonPoints"] = points
        if "+1 Trade Route capacity where NOT city has Market" in row["Modifiers"]:
            b["tradeCapacityUnless"] = "BUILDING_MARKET"  # Lighthouse: only without a Market
            b["tradeCapacity"] = 1
        elif re.search(r"(^|; )\+1 Trade Route capacity($|;)", row["Modifiers"]):
            b["tradeCapacity"] = 1
        slots = {}
        for m in re.finditer(r"(\d+) (\w+)", row["Great Work slots"] or ""):
            slots[m.group(2).upper()] = slots.get(m.group(2).upper(), 0) + int(m.group(1))
        if slots:
            b["greatWorkSlots"] = slots
        if row["Building"] in theming:
            b["theming"] = theming[row["Building"]]
        out.append(b)
    return {"buildings": out}


