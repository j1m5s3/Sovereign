def condition_atom(text):
    """One condition of a combat bonus ('vs Melee', 'NOT when attacking') as JSON."""
    a = {}
    if text.startswith("NOT "):
        a["not"] = True
        text = text[4:]
    m = re.fullmatch(r"vs (.+?)(?: units)?", text)
    tile = re.fullmatch(r"tile is (.+)", text)
    ctype = re.fullmatch(r"combat type matches \(CombatType=Combat (Melee|Ranged)\)", text)
    if text == "when attacking":
        a["atom"] = "ATTACKING"
    elif text == "vs a district/city":
        a["atom"] = "VS_DISTRICT"
    elif m and m.group(1) in ("Land", "Sea", "Air"):
        a.update(atom="VS_DOMAIN", value={"Land": "LAND", "Sea": "SEA", "Air": "AIR"}[m.group(1)])
    elif m:
        a.update(atom="VS_CLASS", value=snake(m.group(1)))
    elif ctype:
        a.update(atom="COMBAT_TYPE", value=ctype.group(1).upper())
    elif tile and tile.group(1) == "Hills":
        a["atom"] = "TILE_HILLS"
    elif tile and tile.group(1) in FEATURE_IDS:
        a.update(atom="TILE_FEATURE", value=FEATURE_IDS[tile.group(1)])
    elif tile and tile.group(1) in terrain_names():
        a.update(atom="TILE_TERRAIN", value=terrain_names()[tile.group(1)])
    elif text == "opponent is fortified":
        a["atom"] = "OPPONENT_FORTIFIED"
    elif text == "opponent is wounded":
        a["atom"] = "OPPONENT_WOUNDED"
    elif text == "plot district is defended":
        a["atom"] = "VS_DISTRICT"
    elif text == "plot has any district":
        a["atom"] = "DISTRICT_TILE"
    elif text == "in own territory":
        a["atom"] = "OWN_TERRITORY"
    elif text == "unit damage minimum (MinimumAmount=1)":
        a["atom"] = "OPPONENT_WOUNDED"
    elif text == "unit in formation":
        a["atom"] = "IN_FORMATION"
    elif text == "attacker plot improvement defense strength (Amount=1)":
        a["atom"] = "TILE_FORT"
    elif text == "plot unit city has any district":
        a["atom"] = "DISTRICT_TILE"
    elif re.fullmatch(r"adjacent to a friendly (\w+) unit", text):  # Drone (05: Support units)
        a.update(atom="NEXT_TO_FRIENDLY_CLASS", value=snake(re.fullmatch(r"adjacent to a friendly (\w+) unit", text).group(1)))
    elif text == "on a coastal tile":
        a["atom"] = "COASTAL_TILE"
    elif text == "on home continent":
        a["atom"] = "HOME_CONTINENT"
    elif text == "opponent is minor civ":
        a["atom"] = "OPPONENT_MINOR"
    elif text == "opponent is free city":
        a["atom"] = "OPPONENT_FREE_CITY"
    elif text in ("unit adjacent to owner territory", "next to friendly territory", "in or next to friendly territory"):
        a["atom"] = "NEAR_OWN_TERRITORY"
    elif re.fullmatch(r"opponent era at least \(MinimumEraType=(\w+) Era\)", text):
        era = re.fullmatch(r"opponent era at least \(MinimumEraType=(\w+) Era\)", text).group(1)
        a.update(atom="OPPONENT_MIN_ERA", value="ERA_" + era.upper())
    else:
        a.update(atom="UNTRACKED", value=text)
    return a


